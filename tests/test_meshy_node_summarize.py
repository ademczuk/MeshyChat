"""`python -m tools.meshy_node summarize`: the node's command for a summary (divergence 037).

Design 1.5, against a recording server (no database, no model):

  * the thread and backlog forms send the parameters the routes read, with a DPoP proof
    bound to exactly this GET and path (a summary is made of bodies; 027's gate);
  * `--since-cursor-file` READS the monitor's sidecar and never writes it: a summary is
    not a delivery, and nothing about it moves the node's cursor;
  * `--text` puts the label on EVERY line, so a copy of any one line carries it;
  * exit codes as cli.py says: 0 on a 200, 1 on any other answer, 2 when the client
    refused before sending (and then nothing was sent).

Run:  pytest tests/test_meshy_node_summarize.py -q     (needs no database)
"""
from __future__ import annotations

