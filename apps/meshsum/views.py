"""GET /v1/mesh/summaries/thread and /v1/mesh/summaries/backlog (divergence 037).

    GET /v1/mesh/summaries/thread?thread_id=<id>[&before=<cursor>][&max_messages=N]
    GET /v1/mesh/summaries/backlog?since=<cursor>|start[&max_messages=N]

The design is docs/design/thread-summaries.md; this module is its section 1.4, THE ORDER
OF THE CHECKS, so that nothing costs HQB or the ledger before the caller is known to be
entitled to it:

  1. authenticate (apps/peers/auth.authenticate_peer), then the route gate: READ on
     shared/mesh-chat (check_permission, about the namespace: NAMESPACE_WIDE, divergence
     040), a 403 with the handler's own code;
  2. the parameters (422, refused and never clamped; `include_inferred` is a 422);
  3. E_SUMMARY_DISABLED unless a passing, verified measurement record exists for this
     summary_version (apps/meshsum/record.py): no ledger row, no tokenizer or model call;
  4. REQUEST admission (apps/meshsum/admission.py): 429, writing no row, past the budget;
  5. one transaction: 027's body gate for THIS caller, asked about the namespace since
     the window is not read yet (`search.namespace_body_withheld`, 403
     E_SUMMARY_WITHHELD), the rows under the per-row rules, and the declared facts;
  6. token counting on the pinned provider (never an estimate; 503 E_CHAT_UNAVAILABLE);
  7. the cache (the model's part only, keyed on the prompt's digest);
  8. MODEL admission (503 E_SUMMARY_BUSY, 429) and the model pin (503
     E_SUMMARY_MODEL_CHANGED);
  9. the model call, to the ONE pinned provider, with every sampler setting;
 10. the re-check, in a short transaction of its own after the call: the body gate again
     and whether each covered row is still the head, still present and still past the gate
     (a sentence citing a changed row is dropped as `source_changed`).

No transaction is held across a network call (019's rule). Every 200 carries `tier:
"generated"`, `unverified: true` and LABEL, written by the server and never by the
model. A dropped sentence's text is never returned. The 502 and the model 503s carry
`facts`: the declared part needs no model, so a node whose summary failed still learns what
it owes.

ROUTE DESIGN: a peer bearer and the `{"error","message"}` envelope extended as the meshsem
503s are.
"""
