#: What every 200 says, in the server's words (design 1.3).
LABEL = ("Generated by a language model from the messages in `covered`. Unverified: it can "
         "be wrong or incomplete. Read the cited messages before acting on any sentence.")
#: The request's wall budget from request admission, and the chat call's ceiling (5.4).
WALL_BUDGET_S = 45.0
CHAT_CEILING_S = 40.0
#: After a provider failure, requests answer 503 at once for this long (5.4).
COOLDOWN_S = 30.0
#: peers.name read for the known labels (validate rule 8), at most this many, held this
#: long (B5, B8).
PEER_NAMES_LIMIT = 10000
PEER_NAMES_TTL_S = 60.0
MAX_THREAD_ID_CHARS = 512

ABSENT_TO_OUTCOME = {"no_text": "no_text", "embed_forbidden": "embed_forbidden",
                     "not_projected": "not_projected", "nothing_new": "nothing_new",
                     "nothing_older": "nothing_new"}


class Answer(Exception):
    """A typed answer after request admission: its status, body, headers, and the ledger
    outcome it settles."""

    def __init__(self, status: int, body: dict, *, outcome: str, headers: dict | None = None,
                 keep_lease: bool = False, settle: dict | None = None):
        super().__init__(body.get("error", ""))
        self.status, self.body, self.outcome = status, body, outcome
        self.headers, self.keep_lease, self.settle = headers or {}, keep_lease, settle or {}


# --------------------------------------------------------------------- cooldowns

_cooldowns: dict[tuple, tuple[float, str]] = {}
_cool_lock = threading.Lock()


def forget_cooldowns() -> None:
    with _cool_lock:
        _cooldowns.clear()


def _cool(provider, why: str) -> None:
    with _cool_lock:
        _cooldowns[(provider.id, provider.base_url)] = (time.monotonic() + COOLDOWN_S, why)


def _cooling(provider) -> tuple[int, str] | None:
    with _cool_lock:
        hit = _cooldowns.get((provider.id, provider.base_url))
    if hit is None:
        return None
    until, why = hit
    left = until - time.monotonic()
    return (int(left) + 1, why) if left > 0 else None


# -------------------------------------------------------------------- parameters

@dataclasses.dataclass(frozen=True)
class Params:
    thread_id: str | None
    before: object
    since: object
    since_raw: str | None
    max_messages: int
    mode: str = "model"


def _parse(request, kind: str) -> Params:
    q = request.GET
    if "include_inferred" in q:
        raise errors.ApiError(422, errors.E_VALIDATION,
                              "a summary reads declared relations only; include_inferred "
                              "is not a parameter here (divergence 037)")
    raw_mode = q.get("mode")
    mode = "model" if raw_mode is None else raw_mode.strip()
    if mode not in ("model", "deterministic"):
        raise errors.ApiError(422, errors.E_VALIDATION, "mode must be model or deterministic")
    raw = q.get("max_messages")
    n = window.DEFAULT_MESSAGES
    if raw is not None:
        try:
            n = int(raw)
        except ValueError:
            raise errors.ApiError(422, errors.E_VALIDATION, "max_messages must be an integer")
        if not 1 <= n <= window.MAX_MESSAGES:
            raise errors.ApiError(422, errors.E_VALIDATION,
                                  f"max_messages must be within 1..{window.MAX_MESSAGES}")
    if kind == "thread":
        thread_id = (q.get("thread_id") or "").strip()
        if not thread_id or len(thread_id) > MAX_THREAD_ID_CHARS:
            raise errors.ApiError(422, errors.E_VALIDATION,
                                  "thread_id is required (at most "
                                  f"{MAX_THREAD_ID_CHARS} characters)")
        before = None
        if q.get("before") is not None:
            before = mesh_wait.decode_cursor(q.get("before"))
            if before is None:
                raise errors.ApiError(422, errors.E_VALIDATION,
                                      "before must be a cursor from a previous response")
        return Params(thread_id=thread_id, before=before, since=None, since_raw=None,
                      max_messages=n, mode=mode)
    since_raw = q.get("since")
    if since_raw is None or since_raw == "":
        raise errors.ApiError(422, errors.E_VALIDATION,
                              "since is required: a /v1/mesh/wait cursor, or `start`")
    if since_raw == "start":
        since = mesh_wait.BEGINNING
    else:
        # A plain `(created_at, id)` cursor, or since STATUS E13 the addressed wait's seq
        # cursor (what `listen --monitor` now saves, and `--since-cursor-file` sends):
        # window.read_backlog places a seq cursor on the walk's own order.
        since = (mesh_wait.decode_cursor(since_raw)
                 or mesh_wait.decode_seq_cursor(since_raw))
        if since is None:
            # The wait reads a malformed cursor as "from now"; here that would be a summary
            # of nothing answered 200, which looks like an empty backlog (design 1.1).
            raise errors.ApiError(422, errors.E_VALIDATION,
                                  "since must be a /v1/mesh/wait cursor or `start`")
    return Params(thread_id=None, before=None, since=since, since_raw=since_raw,
                  max_messages=n, mode=mode)


# ------------------------------------------------------------------------ helpers

_names_memo: dict = {}
_names_lock = threading.Lock()


def _peer_names(conn) -> frozenset:
    now = time.monotonic()
    with _names_lock:
        if _names_memo.get("at") is not None and now - _names_memo["at"] < PEER_NAMES_TTL_S:
            return _names_memo["names"]
    with conn.cursor() as cur:
        cur.execute("SELECT name FROM peers WHERE name IS NOT NULL ORDER BY created_at DESC "
                    "LIMIT %s", (PEER_NAMES_LIMIT,))
        names = frozenset(r[0].strip().lower() for r in cur.fetchall()
                          if isinstance(r[0], str) and r[0].strip())
    with _names_lock:
        _names_memo.update(at=now, names=names)
    return names


def _pinned_provider(rec):
    eligible, refused = providers.content_providers("chat")
    for p in eligible:
        if p.id == rec.provider_id:
            return p, []
    attempts = [a for a in refused if a.get("id") == rec.provider_id] or [
        {"id": rec.provider_id, "verdict": "not_declared",
         "reason": "the measured provider is not declared as a chat provider"}]
    return None, attempts


def _unavailable(message: str, attempts, facts_: dict, *, retry_after: int | None = None,
                 keep_lease: bool = False) -> Answer:
    headers = {"Retry-After": str(retry_after)} if retry_after else {}
    return Answer(503, {"error": "E_CHAT_UNAVAILABLE", "message": message,
                        "attempts": search.wire_attempts(attempts), "facts": facts_},
                  outcome="unavailable", headers=headers, keep_lease=keep_lease)


def _rejected(refused: str, facts_: dict, *, drop_reasons: dict | None = None,
              message: str | None = None) -> Answer:
    return Answer(502, {"error": "E_SUMMARY_REJECTED",
                        "message": message or f"the model's answer was refused whole: "
                                              f"{refused}",
                        "refused": refused, "drop_reasons": drop_reasons or {},
                        "facts": facts_},
                  outcome="rejected",
                  settle={"drop_reasons": drop_reasons or {refused: 1}})


def _from_refused(exc: admission.Refused, facts_: dict | None = None) -> Answer:
    body = exc.body()
    if facts_ is not None:
        body["facts"] = facts_
    return Answer(exc.status, body, outcome=exc.outcome,
                  headers={"Retry-After": str(exc.retry_after)})


def _transport(attempts) -> bool:
    """Whether a failed chat attempt was a TRANSPORT failure (a timeout, a reset): HQB may
    still be generating, so the call keeps its lease (critique C15)."""
    return any(str(a.get("reason", "")).startswith(("unreachable:", "transport:"))
               for a in attempts or ())


def _absent(kind: str, cands) -> str:
    if kind == "thread":
        if cands.declared_total == 0 and cands.unprojected > 0:
            return "not_projected"
        if cands.in_scope == 0:
            return "nothing_older"
    elif not cands.scanned:
        return "nothing_new"
    forbidden = cands.excluded.get("embed_forbidden", 0)
    no_text = cands.excluded.get("no_text", 0)
    if forbidden and not no_text:
        return "embed_forbidden"
    if no_text and not forbidden:
        return "no_text"
    return "embed_forbidden" if forbidden else "no_text"


def _changed(conn, rows: list, gate_open: bool) -> set[int]:
    """Numbers of covered rows that are no longer what the model was shown: gone, no
    longer the head, another version, or kept from the model by the gate now."""
    ids = [str(r.id) for r in rows]
    with conn.cursor() as cur:
        cur.execute("SELECT id, version, is_head, embed_policy FROM shared_memory "
                    "WHERE id = ANY(%s::uuid[])", (ids,))
        now = {str(i): (v, h, p) for i, v, h, p in cur.fetchall()}
    out: set[int] = set()
    for n, r in enumerate(rows, start=1):
        cur_row = now.get(str(r.id))
        if (cur_row is None or not cur_row[1] or cur_row[0] != r.version
                or (cur_row[2] != "allowed" and not gate_open)):
            out.add(n)
    return out


def _roles(rows: list) -> dict:
    out = {"to": 0, "cc": 0, "broadcast": 0}
    for r in rows:
        if r.role in out:
            out[r.role] += 1
    return out


def _now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat()


# ---------------------------------------------------------------------- the route

def _route(route_name: str, kind: str):
    def view(request):
        if request.method != "GET":
            return HttpResponse(status=405, headers={"Allow": "GET"})
        try:
            with dbconn.serving_connection() as conn:
                auth = authenticate_peer(conn, request)
                # B12 (the project's design log (not part of this release) 003): the peer's CALLS bucket, before the read gate,
                # the summary and its usage row.
                peer_limit.admit(auth.peer_id, transport="mesh")
                outcome = "error"
                try:
                    with dbconn.request_server_internal(conn) as c:
                        try:
                            check_permission(MESH_CHAT_NAMESPACE, auth.peer_id, "read", c,
                                             resource=NAMESPACE_WIDE)
                        except HandlerError as exc:
                            outcome = "denied"
                            return JsonResponse({"error": exc.code, "message": exc.message},
                                                status=403)
                    response = _summarize(request, conn, auth, kind)
                    outcome = "ok" if response.status_code == 200 else "error"
                    return response
                finally:
                    # In a transaction of its own, after the read's (apps/mesh/usage.py).
                    usage.record(conn, route_name, auth.peer_id, outcome)
        except peer_limit.PeerRateLimited as exc:
            return peer_limit.http_response(exc)
        except errors.ApiError as exc:
            return JsonResponse(exc.body(), status=exc.status)
    view.__name__ = kind
    return csrf_exempt(view)


def _summarize_deterministic(request, conn, auth, kind: str, params: Params) -> JsonResponse:
    """In-process extractive digest + declared `facts` with zero LLM/provider/tokenizer calls.
    Skips `admission.admit_request` (`mesh_summary_requests` tracks HQB model-call leases/budgets),
    while `_route` still enforces `peer_limit.admit` and records `mesh_route_usage` (`usage.record`)."""
    started = time.monotonic()
    gate = store.forbidden_rows_open()
    reader = meshsem_views.reader_for_request(conn, request, auth)
    with dbconn.request_server_internal(conn) as c:
        withheld = search.namespace_body_withheld(c, reader)
        if withheld is not None:
            return JsonResponse({
                "error": "E_SUMMARY_WITHHELD",
                "message": "memory.read would not show this caller these messages, so no summary "
                           "of them is shown (divergence 027's gate)",
                "body_withheld": withheld,
            }, status=403)
        labels = [x["label"] for x in mesh_views.labels_for(c, auth.peer_id)]
        if kind == "thread":
            cands = window.read_thread(c, params.thread_id, before=params.before,
                                       max_messages=params.max_messages, gate_open=gate)
            if cands.declared_total == 0 and cands.unprojected == 0:
                return JsonResponse({"error": errors.E_NOT_FOUND,
                                     "message": "no head message declares this thread"}, status=404)
            facts_ = facts.for_thread(c, params.thread_id, labels)
        else:
            cands = window.read_backlog(c, auth.peer_id, since=params.since,
                                        max_messages=params.max_messages, gate_open=gate)
            facts_ = facts.for_backlog(c, cands.scanned, labels)

    rows = window._present(cands.rows) if cands.rows else []
    scope = ({"kind": "thread", "thread_id": params.thread_id} if kind == "thread" else
             {"kind": "backlog", "since": params.since_raw, "roles": _roles(rows)})
    composed = window.compose(rows, kind, names=cands.names, thread_id=params.thread_id) if rows else None
    sentences = deterministic.extract_sentences(rows) if rows else []
    absent = _absent(kind, cands) if not rows else None
    latency_ms = int((time.monotonic() - started) * 1000)

    if kind == "thread":
        if rows:
            oldest, newest = rows[0], rows[-1]
            older = cands.in_scope - cands.scan_index[str(oldest.id)] - 1
            win = {"covered": len(rows), "older_not_covered": older,
                   "unprojected": cands.unprojected,
                   "before": oldest.cursor() if older > 0 else None,
                   "through": newest.cursor(), "more": False,
                   "scan_limited": cands.scan_limited}
        else:
            win = {"covered": 0, "older_not_covered": max(0, cands.in_scope - cands.scanned_count),
                   "unprojected": cands.unprojected, "before": None, "through": None,
                   "more": False, "scan_limited": cands.scan_limited}
    else:
        position = cands.position or params.since
        win = {"covered": len(rows), "through": mesh_wait.cursor_wire(position),
               "more": bool(cands.scan_more)}

    return JsonResponse({
        "tier": "deterministic_extractive",
        "mode": "deterministic",
        "unverified": True,
        "label": deterministic.DETERMINISTIC_LABEL,
        "scope": scope,
        "window": win,
        "covered": composed.covered if composed is not None else [],
        "covered_digest": composed.covered_digest if composed is not None else None,
        "excluded": {"embed_forbidden": cands.excluded.get("embed_forbidden", 0),
                     "no_text": cands.excluded.get("no_text", 0),
                     "cut_to_fit": 0,
                     "source_changed": 0},
        "rendering": {"escaped_characters": composed.escaped if composed else 0,
                      "unrenderable_fields": composed.unrenderable if composed else 0},
        "facts": facts_,
        "summary": {"sentences": sentences, "dropped": [], "absent": absent},
        "provenance": {
            "mode": "deterministic",
            "model": None,
            "model_reported": None,
            "model_pin": None,
            "provider_id": None,
            "summary_version": deterministic.DETERMINISTIC_SUMMARY_VERSION,
            "generated_at": _now(),
            "finish_reason": "extractive",
            "latency_ms": latency_ms,
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "cache": None,
            "attempts": [],
        },
    }, status=200)


def _summarize(request, conn, auth, kind: str) -> JsonResponse:
    params = _parse(request, kind)
    if params.mode == "deterministic":
        return _summarize_deterministic(request, conn, auth, kind, params)
    rec, why = record.current()
    if rec is None:
        return JsonResponse({
            "error": "E_SUMMARY_DISABLED",
            "message": "summaries are served only for a summary_version and model pin that "
                       "passed their measurement (docs/design/thread-summaries.md 7.8)",
            "summary_version": P.SUMMARY_VERSION, "reason": why}, status=503)
    reader = meshsem_views.reader_for_request(conn, request, auth)
    try:
        adm = admission.admit_request(conn, peer_id=auth.peer_id, scope_kind=kind,
                                      summary_version=P.SUMMARY_VERSION,
                                      limits=admission.LIMITS)
    except admission.Refused as exc:
        a = _from_refused(exc)
        return JsonResponse(a.body, status=a.status, headers=a.headers)
    try:
        return _admitted(conn, auth, kind, params, rec, reader, adm)
    except Answer as a:
        admission.settle(conn, adm.request_id, outcome=a.outcome, keep_lease=a.keep_lease,
                         **{k: v for k, v in a.settle.items() if k != "drop_reasons"},
                         drop_reasons=a.settle.get("drop_reasons"),
                         model_pin=rec.model_pin, provider_id=rec.provider_id)
        return JsonResponse(a.body, status=a.status, headers=a.headers)
    except BaseException:
        admission.settle(conn, adm.request_id, outcome="error")
        raise


def _admitted(conn, auth, kind: str, params: Params, rec, reader, adm) -> JsonResponse:
    started = time.monotonic()
    deadline = started + WALL_BUDGET_S
    gate = store.forbidden_rows_open()

    # 5. One transaction: the body gate, the rows, the facts (2.2, 2.3, 4.4).
    with dbconn.request_server_internal(conn) as c:
        withheld = search.namespace_body_withheld(c, reader)
        if withheld is not None:
            raise Answer(403, {"error": "E_SUMMARY_WITHHELD",
                               "message": "memory.read would not show this caller these "
                                          "messages, so no summary of them is shown "
                                          "(divergence 027's gate)",
                               "body_withheld": withheld}, outcome="withheld")
        labels = [x["label"] for x in mesh_views.labels_for(c, auth.peer_id)]
        if kind == "thread":
            cands = window.read_thread(c, params.thread_id, before=params.before,
                                       max_messages=params.max_messages, gate_open=gate)
            if cands.declared_total == 0 and cands.unprojected == 0:
                raise Answer(404, {"error": errors.E_NOT_FOUND,
                                   "message": "no head message declares this thread"},
                             outcome="not_found")
            facts_ = facts.for_thread(c, params.thread_id, labels)
        else:
            cands = window.read_backlog(c, auth.peer_id, since=params.since,
                                        max_messages=params.max_messages, gate_open=gate)
            facts_ = facts.for_backlog(c, cands.scanned, labels)
        peer_names = _peer_names(c)

    scope = ({"kind": "thread", "thread_id": params.thread_id} if kind == "thread" else
             {"kind": "backlog", "since": params.since_raw, "roles": _roles([])})
    if not cands.rows:
        absent = _absent(kind, cands)
        admission.settle(conn, adm.request_id, outcome=ABSENT_TO_OUTCOME[absent],
                         covered_count=0, excluded=cands.excluded,
                         model_pin=rec.model_pin, provider_id=rec.provider_id)
        return JsonResponse(_body(kind, scope, cands, None, None, facts_, rec, provider=None,
                                  sentences=[], dropped=[], absent=absent, provenance={},
                                  how=None, source_changed=0, params=params), status=200)

    # 6. Token counting, on the pinned provider only.
    provider, attempts = _pinned_provider(rec)
    if provider is None:
        raise _unavailable("the measured chat provider is not available", attempts, facts_)
    cooling = _cooling(provider)
    if cooling is not None:
        raise _unavailable(f"the chat provider is cooling down after a failure: {cooling[1]}",
                           [{"id": provider.id, "verdict": "not_tried",
                             "reason": "cooling down"}], facts_, retry_after=cooling[0])
    counter = window.TokenCounter(provider, rec.model_pin, deadline=deadline)
    try:
        packed = window.pack(cands, counter)
    except window.TokenizeFailed as exc:
        _cool(provider, str(exc))
        raise _unavailable("the chat provider could not count tokens", exc.attempts, facts_,
                           retry_after=int(COOLDOWN_S))
    if not packed.rows:
        raise _rejected("nothing_fits", facts_,
                        message="not even one message fits the model's window")
    composed = window.compose(packed.rows, kind, names=cands.names,
                              thread_id=params.thread_id)
    if any(V.fold(composed.nonce) in V.fold(s.body) for s in composed.sources):
        # 128 bits a writer cannot predict: a body holding it is refused, not sent (3.2).
        raise _rejected("nonce_in_body", facts_)
    known = set(peer_names)
    for s in composed.sources:
        known |= set(s.aliases) | {x.lower() for x in s.to} | {x.lower() for x in s.cc}
    ctx = V.Context(sources=composed.sources, known_labels=frozenset(known),
                    system_text=composed.messages[0]["content"], canary=composed.canary,
                    nonce=composed.nonce)

    # 7 to 9. The cache, then model admission, the pin and the call (a miss's leader only).
    key = cache.cache_key(kind=kind, prompt_digest=composed.prompt_digest,
                          summary_version=P.SUMMARY_VERSION, model_pin=rec.model_pin,
                          provider_id=rec.provider_id)

    def compute() -> cache.ModelPart:
        # An Answer raised here is the LEADER'S: `single_flight` re-raises it unchanged to
        # `_summarize`'s `except Answer`, and hands each waiter `LeaderFailed(cause=
        # Answer)`, answered below with the leader's status and body.
        admission.admit_model_call(conn, adm.request_id, peer_id=auth.peer_id,
                                   owner_id=adm.owner_id, limits=admission.LIMITS)
        try:
            live = pin.current_pin(provider)
        except pin.PinUnavailable as exc:
            _cool(provider, str(exc))
            raise _unavailable("the chat provider did not describe itself",
                               [{"id": provider.id, "verdict": "failed",
                                 "reason": f"pin: {exc}"}], facts_,
                               retry_after=int(COOLDOWN_S))
        except pin.PinIncomplete as exc:
            raise _model_changed(f"the provider did not report {exc}", facts_)
        if live.digest != rec.model_pin:
            raise _model_changed("the provider no longer reports the measured model",
                                 facts_)
        remaining = max(0.1, deadline - time.monotonic())
        t0 = time.monotonic()
        try:
            reply = providers.chat(composed.messages, provider_ids={rec.provider_id},
                                   max_tokens=P.REQUEST["max_tokens"], params=P.REQUEST,
                                   json_schema=P.json_schema(len(packed.rows)),
                                   accept_empty=True, budget_s=remaining,
                                   timeout_s=min(CHAT_CEILING_S, remaining))
        except providers.ChatUnavailable as exc:
            _cool(provider, "chat failed")
            raise _unavailable("the chat provider did not answer", exc.attempts, facts_,
                               retry_after=int(COOLDOWN_S),
                               keep_lease=_transport(exc.attempts))
        latency = int((time.monotonic() - t0) * 1000)
        usage_ = reply.usage or {}
        provenance = {"model_reported": reply.model, "finish_reason": reply.finish_reason,
                      "latency_ms": latency, "generated_at": _now(),
                      "prompt_tokens": usage_.get("prompt_tokens"),
                      "completion_tokens": usage_.get("completion_tokens"),
                      "attempts": search.wire_attempts(reply.attempts)}
        verdict = V.validate(reply.text, reply.finish_reason, ctx)
        if verdict.refused is None:
            verdict = V.settle(verdict, changed=set())      # the half rule, before caching
        if verdict.refused is not None:
            a = _rejected(verdict.refused, facts_, drop_reasons=verdict.histogram())
            a.settle.update(latency_ms=latency, finish_reason=reply.finish_reason,
                            prompt_tokens=usage_.get("prompt_tokens"),
                            completion_tokens=usage_.get("completion_tokens"))
            raise a
        return cache.ModelPart(kept=verdict.kept, dropped=verdict.dropped,
                               total=verdict.total, provenance=provenance)

    try:
        part, how = cache.CACHE.single_flight(
            key, compute, wait_s=max(0.1, deadline - time.monotonic()),
            retry_on=lambda e: isinstance(e, admission.Refused) and e.status == 429)
    except admission.Refused as exc:
        raise _from_refused(exc, facts_)
    except cache.LeaderFailed as exc:
        cause = exc.cause
        if isinstance(cause, admission.Refused):
            raise _from_refused(cause, facts_)
        if isinstance(cause, Answer):
            # The leader's answer, settled as this request's: the drop reasons only, since
            # the latency and the tokens were the leader's call, and this one made none.
            a = cause
            raise Answer(a.status, a.body, outcome=a.outcome, headers=a.headers,
                         settle={k: v for k, v in a.settle.items()
                                 if k == "drop_reasons"})
        raise _unavailable("the request this one waited on failed",
                           [{"id": provider.id, "verdict": "failed",
                             "reason": type(cause).__name__}], facts_)
    except cache.WaitTimedOut:
        raise _unavailable("the request this one waited on did not finish in time",
                           [{"id": provider.id, "verdict": "not_tried",
                             "reason": "waited on another request's call"}], facts_)

    # 10. The re-check, after a call (made or waited on): never across one.
    changed: set[int] = set()
    if how in ("miss", "shared"):
        with dbconn.request_server_internal(conn) as c:
            withheld = search.namespace_body_withheld(c, reader)
            if withheld is not None:
                raise Answer(403, {"error": "E_SUMMARY_WITHHELD",
                                   "message": "memory.read no longer shows this caller "
                                              "these messages",
                                   "body_withheld": withheld}, outcome="withheld")
            changed = _changed(c, packed.rows, store.forbidden_rows_open())
    verdict = V.settle(V.Verdict(kept=part.kept, dropped=part.dropped, total=part.total),
                       changed)
    if verdict.refused is not None:
        raise _rejected(verdict.refused, facts_, drop_reasons=verdict.histogram())

    key_of = {n: r.key for n, r in enumerate(packed.rows, start=1)}
    sentences = [{"text": s.text, "cites": [key_of[c] for c in s.cites]}
                 for s in verdict.kept]
    dropped = [{"position": d.position, "reason": d.reason,
                "cites": [key_of[c] for c in d.cites if c in key_of]}
               for d in verdict.dropped]
    source_changed = sum(1 for d in verdict.dropped if d.reason == V.SOURCE_CHANGED)
    absent = "model_returned_none" if verdict.total == 0 else None
    prov = dict(part.provenance)
    admission.settle(conn, adm.request_id, outcome="generated" if how == "miss" else
                     "cache_hit", covered_digest=composed.covered_digest,
                     covered_count=len(packed.rows),
                     excluded={**cands.excluded, "cut_to_fit": packed.cut_to_fit,
                               "source_changed": source_changed},
                     sentences_kept=len(verdict.kept), sentences_dropped=len(verdict.dropped),
                     drop_reasons=verdict.histogram(), model_pin=rec.model_pin,
                     provider_id=rec.provider_id,
                     latency_ms=prov.get("latency_ms") if how == "miss" else None,
                     prompt_tokens=prov.get("prompt_tokens") if how == "miss" else None,
                     completion_tokens=prov.get("completion_tokens") if how == "miss"
                     else None, finish_reason=prov.get("finish_reason"))
    if kind == "backlog":
        scope["roles"] = _roles(packed.rows)
    return JsonResponse(_body(kind, scope, cands, packed, composed, facts_, rec,
                              provider=provider, sentences=sentences, dropped=dropped,
                              absent=absent, provenance=prov, how=how,
                              source_changed=source_changed, params=params), status=200)


def _model_changed(message: str, facts_: dict) -> Answer:
    return Answer(503, {"error": "E_SUMMARY_MODEL_CHANGED", "message": message,
                        "facts": facts_}, outcome="model_changed")


def _body(kind, scope, cands, packed, composed, facts_, rec, *, provider, sentences,
          dropped, absent, provenance, how, source_changed, params) -> dict:
    rows = packed.rows if packed is not None else []
    if kind == "thread":
        if rows:
            oldest, newest = rows[0], rows[-1]
            older = cands.in_scope - cands.scan_index[str(oldest.id)] - 1
            win = {"covered": len(rows), "older_not_covered": older,
                   "unprojected": cands.unprojected,
                   "before": oldest.cursor() if older > 0 else None,
                   "through": newest.cursor(), "more": False,
                   "scan_limited": cands.scan_limited}
        else:
            win = {"covered": 0, "older_not_covered": max(0, cands.in_scope -
                                                          cands.scanned_count),
                   "unprojected": cands.unprojected, "before": None, "through": None,
                   "more": False, "scan_limited": cands.scan_limited}
    else:
        if rows and packed.unpacked:
            through, more = rows[-1].cursor(), True
        else:
            position = cands.position or params.since
            through = mesh_wait.cursor_wire(position)
            more = bool(cands.scan_more)
        win = {"covered": len(rows), "through": through, "more": more}
    return {
        "tier": "generated",
        "unverified": True,
        "label": LABEL,
        "scope": scope,
        "window": win,
        "covered": composed.covered if composed is not None else [],
        "covered_digest": composed.covered_digest if composed is not None else None,
        "excluded": {"embed_forbidden": cands.excluded.get("embed_forbidden", 0),
                     "no_text": cands.excluded.get("no_text", 0),
                     "cut_to_fit": packed.cut_to_fit if packed is not None else 0,
                     "source_changed": source_changed},
        "rendering": {"escaped_characters": composed.escaped if composed else 0,
                      "unrenderable_fields": composed.unrenderable if composed else 0},
        "facts": facts_,
        "summary": {"sentences": sentences, "dropped": dropped, "absent": absent},
        "provenance": {
            "model": (provider.model or None) if provider is not None else None,
            "model_reported": provenance.get("model_reported"),
            "model_pin": rec.model_pin, "provider_id": rec.provider_id,
            "summary_version": P.SUMMARY_VERSION,
            "generated_at": provenance.get("generated_at"),
            "finish_reason": provenance.get("finish_reason"),
            "latency_ms": provenance.get("latency_ms"),
            "prompt_tokens": provenance.get("prompt_tokens"),
            "completion_tokens": provenance.get("completion_tokens"),
            "cache": how,
            "attempts": provenance.get("attempts", []),
        },
    }


